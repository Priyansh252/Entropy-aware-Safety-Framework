"""Run an experiment (or load an existing one) and write a Markdown report from the MEASURED summary.
Usage:  python scripts/make_report.py [--trials 100] [--seed 42] [--out docs/SAMPLE_EXPERIMENT_REPORT.md]
Nothing in the report is typed by hand: every number comes from summary.json of the run."""
import argparse, json, shutil, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from backend.core import experiments as X
from backend.storage import db


def ci(r):
    return f"{r['rate']*100:.1f}% (95% CI {r['ci_low']*100:.1f}-{r['ci_high']*100:.1f}%, n={r['n']})" if r and r.get("rate") is not None else "n/a"


def build(s, eid):
    g, p = s["groups"], s["params"]
    L = [f"# Sample experiment report ({eid})", "",
         "Generated by `scripts/make_report.py` from the measured `summary.json` of this run. Educational key sizes and **simulated** fault models; this is not evidence of production security.", "",
         f"- Trials requested: {p['trials']} (effective per group: " + ", ".join(f"{k}={v['effective_trials']}" for k, v in g.items()) + ")",
         f"- Seed {p['seed']}, fault model `{p['fault_mode']}` at p={p['fault_probability']}, {p['signatures_per_session']} signatures/session, {p['rsa_keys_per_population']} RSA keys/population, {p['key_bits']}-bit moduli",
         f"- Environment: Python {s['environment']['python']}, cryptography {s['environment']['cryptography']}, {s['environment']['platform']}", ""]
    if "ecdsa_attack" in g:
        m = g["ecdsa_attack"]["metrics"]
        L += ["## ECDSA nonce reuse", f"- Key recovery with normal random nonces: {ci(m['attack_success_normal'])}", f"- Key recovery with a reused nonce: {ci(m['attack_success_reused'])}",
              f"- Reuse detection rate (signature analysis): {ci(m['detection']['detection_rate'])}; false-positive rate: {ci(m['detection']['false_positive_rate'])}", ""]
    if "ecdsa_defense" in g:
        m = g["ecdsa_defense"]["metrics"]
        L += ["## ECDSA: baseline vs defended signing", "| Arm | Sessions compromised | Reused-nonce signatures accepted | Rejected candidates | Regenerations | Fallbacks | Mean ms/signature |", "|---|---|---|---|---|---|---|"]
        for a, v in m.items():
            L.append(f"| {a} | {ci(v['sessions_compromised'])} | {v['vulnerable_signatures_accepted']} | {v['candidates_rejected']} | {v['regenerations']} | {v['fallbacks']} | {v['time_ms_per_signature']['mean']:.4f} |")
        L.append("")
    if "rsa_batch_gcd" in g:
        m = g["rsa_batch_gcd"]["metrics"]
        L += ["## RSA batch GCD", f"- Modulus-level detection rate: {ci(m['modulus_level']['detection_rate'])}", f"- False-positive rate: {ci(m['modulus_level']['false_positive_rate'])}", f"- Verified factor recoveries: {ci(m['factor_recovery_verified'])}", f"- Agreement with pairwise GCD: {ci(m['batch_vs_pairwise_agreement'])}", ""]
    if "rsa_defense" in g:
        m = g["rsa_defense"]["metrics"]
        L += ["## RSA: baseline vs defended generation", "| Arm | Vulnerable final keys | Keys factored by batch GCD | Candidates | Rejected | Fallbacks | Mean ms/key |", "|---|---|---|---|---|---|---|"]
        for a, v in m.items():
            L.append(f"| {a} | {v['vulnerable_final_keys']} ({ci(v['vulnerable_final_rate'])}) | {ci(v['keys_factored_by_batch_gcd'])} | {v['candidates_generated']} | {v['candidates_rejected']} | {v['fallbacks']} | {v['time_ms_per_key']['mean']:.3f} |")
        L += ["", "_Timing caveat: primes are pre-generated, so the baseline time excludes key generation; the per-key ms above is validation/decision cost, and the overhead relative to real key generation is reported in the Overhead section._", ""]
    if "threshold_sensitivity" in g:
        m = g["threshold_sensitivity"]["metrics"]
        L += ["## Risk-threshold sensitivity (soft factors only; simulated contexts)", f"{m['contexts']} synthetic contexts, {m['vulnerable_contexts']} with a weak source.", "", "| Profile | Threshold | Detection | False rejection |", "|---|---|---|---|"]
        L += [f"| {x['profile']} | {x['threshold']} | {x['detection_rate']*100:.1f}% | {x['false_rejection_rate']*100:.1f}% |" for x in m["grid"]]
        L += ["", "Reading: the score alone separates weak from healthy sources only partially, and lowering the threshold trades detection against false rejection. This is why confirmed nonce reuse and shared primes are handled by hard-fail rules, not by the score.", ""]
    if "overhead" in g:
        m = g["overhead"]["metrics"]
        L += ["## Overhead (this machine)"] + [f"- {k}: {v['mean']:.4f} ms mean (median {v['median']:.4f})" for k, v in m["signing_ms"].items()]
        L += [f"- RSA key generation: {m['rsa_keygen_ms']['mean']:.2f} ms; validation + scoring: {m['rsa_validation_ms']['mean']:.2f} ms ({m['rsa_validation_overhead_pct']:.0f}% of key-generation time)", ""]
    if "adaptive_policy" in g:
        m = g["adaptive_policy"]["metrics"]
        L += ["## Adaptive policy", f"- {m['scenarios']} requirement combinations enumerated; selections below the required security level: **{m['selections_below_required_security']}**; combinations with no eligible configuration (refused rather than weakened): {m['no_eligible_configuration']}", f"- Chosen: {m['selected_counts']}", ""]
    if "entropy_samples" in g:
        L += ["## Entropy samples", "| Sample | Mean bits/byte | Low-entropy flag | Repeated-block flag |", "|---|---|---|---|"]
        L += [f"| {k} | {v['shannon_bits']['mean']:.3f} | {v['low_entropy_flag_rate']['rate']*100:.0f}% | {v['repeated_block_flag_rate']['rate']*100:.0f}% |" for k, v in g["entropy_samples"]["metrics"].items()]
        L.append("")
    L += ["## Limitations", "- Fault models are simulated; keys are educational sizes; timings are machine dependent.", "- The generation-time RSA check only compares candidates with moduli it has already seen.", "- The ECDSA reuse registry covers one signer instance; deterministic signing is the robust option."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--trials", type=int, default=100)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default="docs/SAMPLE_EXPERIMENT_REPORT.md")
    a = ap.parse_args()
    db.init_db()
    eid = X.run_experiment_sync({"trials": a.trials, "seed": a.seed})
    e = db.get_experiment(eid)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build(e["summary"], eid), encoding="utf-8")
    shutil.copy(e["csv_path"], out.parent / "sample_raw_results.csv")
    shutil.copy(e["json_path"], out.parent / "sample_summary.json")
    print("wrote", out, "from", eid)
